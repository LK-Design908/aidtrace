"""Pooled six-country model vs per-country models (same features, same temporal folds).

    python -I -m aidtrace_pipeline.pooled            # after `model --country X` has run for each country

Pooling lets low-violence countries (Djibouti, Kenya) borrow strength from the others. A one-hot
country indicator lets the model keep country-specific base rates. Results are written to
docs/model_results_pooled.md; per-country predictions come from each country's model run.
"""
from __future__ import annotations

import logging

import numpy as np
import pandas as pd

from .common import PROCESSED, cfg, log, path
from .model import MC, Dataset, dataset, expanding_cv, metrics, within_month_auc

COUNTRIES = ["SOM", "ETH", "KEN", "SSD", "SDN", "DJI"]


def iso3_of(unit_id: pd.Series) -> pd.Series:
    m = {c["iso2"]: k for k, c in cfg()["countries"].items()}
    return unit_id.str[:2].map(m)


def run() -> pd.DataFrame:
    rows = []
    for h in MC()["horizons"]:
        pooled = expanding_cv(pooled_dataset(h), ["lightgbm"])
        pooled["country"] = iso3_of(pooled["unit_id"])
        pooled.to_parquet(path(PROCESSED) / "model" / f"cv_predictions_pooled_h{h}.parquet", index=False)
        for iso in COUNTRIES:
            own_p = path(PROCESSED) / "model" / f"cv_predictions_{iso.lower()}_h{h}.parquet"
            own = pd.read_parquet(own_p) if own_p.exists() else pd.DataFrame()
            for label, d in [("per-country LightGBM", own[own["model"] == "lightgbm"] if len(own) else own),
                             ("per-country logistic", own[own["model"] == "logit"] if len(own) else own),
                             ("per-country persistence", own[own["model"] == "persistence"] if len(own) else own),
                             ("pooled LightGBM", pooled[pooled["country"] == iso])]:
                if d.empty:
                    continue
                m = metrics(d, MC()["alert_rate"])
                rows.append({"horizon": h, "country": iso, "model": label, "n": m["n"], "base_rate": m["base_rate"],
                             "auc": m["auc"], "auc_within_month": within_month_auc(d) if m["base_rate"] > 0 else np.nan,
                             "brier": m["brier"]})
    out = pd.DataFrame(rows)
    write_report(out)
    return out


POOLED_MODEL = "lightgbm_bagged_pooled_no_acled"


def pooled_dataset(h: int) -> Dataset:
    frames = [dataset(iso, h, use_acled=False).frame for iso in COUNTRIES]
    f = pd.concat(frames, ignore_index=True)
    f["country"] = iso3_of(f["unit_id"])
    for iso in COUNTRIES:
        f[f"cty_{iso}"] = (f["country"] == iso).astype(int)
    feats = [c for c in f.columns if c not in ("unit_id", "origin", "target_month", "y", "country")]
    return Dataset(f, feats)


def score() -> dict:
    """Risk scores for every country from one bagged pooled model (pipeline.yaml model.scoring = pooled).
    Writes data/processed/risk/<iso>_risk.parquet, the files the server reads."""
    from .model import score_latest
    out_dir = path(PROCESSED) / "risk"
    out_dir.mkdir(parents=True, exist_ok=True)
    parts = []
    for h in MC()["horizons"]:
        ds = pooled_dataset(h)
        parts.append(score_latest("ALL", h, ds, model_name=POOLED_MODEL))
    risk = pd.concat(parts, ignore_index=True)
    risk["country"] = iso3_of(risk["unit_id"])
    summary = {}
    for iso, d in risk.groupby("country"):
        d = d.drop(columns="country")
        if iso == "DJI":   # one fatal event in the 2021-2025 test years: scores are not meaningful
            d["note"] = d["note"] + " Not evaluable for Djibouti (too few recorded events): do not interpret bands."
        d.to_parquet(out_dir / f"{iso.lower()}_risk.parquet", index=False)
        summary[iso] = {"units": int(d["unit_id"].nunique()), "origin": f"{d['origin'].max():%Y-%m}",
                        "bands_h1": d[d["horizon"] == 1]["band"].value_counts().to_dict()}
    return summary


def _f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def write_report(t: pd.DataFrame) -> None:
    L = ["<!-- AUTO-GENERATED by `python -m aidtrace_pipeline.pooled`. -->",
         "# Pooled vs per-country models (CV 2021–2025, target: ≥1 fatal UCDP event)\n",
         "Same features and folds for every model. AUC is n/a where a country has no events in the test years.\n",
         "| Horizon | Country | Model | n | Base rate | AUC | Within-month AUC | Brier |", "|---|---|---|---|---|---|---|---|"]
    for _, r in t.sort_values(["horizon", "country", "model"]).iterrows():
        L.append(f"| {r.horizon} | {r.country} | {r.model} | {r.n} | {_f(r.base_rate)} | {_f(r.auc)} | "
                 f"{_f(r.auc_within_month)} | {_f(r.brier)} |")
    (path("docs") / "model_results_pooled.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    import argparse
    import json
    ap = argparse.ArgumentParser()
    ap.add_argument("--score", action="store_true", help="write risk scores for all countries from the pooled model")
    ap.add_argument("--no-eval", action="store_true", help="skip the pooled vs per-country evaluation")
    a = ap.parse_args()
    logging.basicConfig(level=logging.INFO)
    if a.score:
        print(json.dumps(score(), indent=2))
    if a.no_eval:
        raise SystemExit(0)
    res = run()
    log.info("pooled comparison written to docs/model_results_pooled.md")
    print(res.pivot_table(index=["horizon", "country"], columns="model", values="auc").round(3).to_string())
